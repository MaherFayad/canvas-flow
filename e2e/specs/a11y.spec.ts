/**
 * axe-core over the extension UI (not the app inside the frames) in three views:
 * Player, Canvas with the edge inspector open, and the Tokens panel.
 *
 * This spec does not fail on violations: the components are owned elsewhere and
 * fixed there. It writes every violation, with selector and WCAG 2.2 success
 * criterion, to e2e/a11y-report.md, and fails only if axe itself cannot run.
 */
import fs from 'node:fs';
import path from 'node:path';
import AxeBuilder from '@axe-core/playwright';
import { demoConfig, expect, test, type Canvas } from '../fixtures';
import { DEMO, E2E_DIR } from '../fixtures/paths';

const TAGS = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa', 'best-practice'];

/** WCAG 2.2 success criteria names for the criteria axe reports on. */
const SC: Record<string, string> = {
  '1.1.1': 'Non-text Content (A)',
  '1.3.1': 'Info and Relationships (A)',
  '1.3.5': 'Identify Input Purpose (AA)',
  '1.4.1': 'Use of Color (A)',
  '1.4.3': 'Contrast (Minimum) (AA)',
  '1.4.4': 'Resize Text (AA)',
  '1.4.11': 'Non-text Contrast (AA)',
  '1.4.12': 'Text Spacing (AA)',
  '2.1.1': 'Keyboard (A)',
  '2.1.3': 'Keyboard (No Exception) (AAA)',
  '2.4.1': 'Bypass Blocks (A)',
  '2.4.2': 'Page Titled (A)',
  '2.4.4': 'Link Purpose (In Context) (A)',
  '2.5.3': 'Label in Name (A)',
  '2.5.8': 'Target Size (Minimum) (AA)',
  '3.1.1': 'Language of Page (A)',
  '3.3.2': 'Labels or Instructions (A)',
  '4.1.2': 'Name, Role, Value (A)',
};

interface Row {
  view: string;
  id: string;
  impact: string;
  criteria: string[];
  help: string;
  url: string;
  targets: string[];
}

const criteriaOf = (tags: string[]) =>
  tags
    .map((t) => /^wcag(\d)(\d)(\d+)$/.exec(t))
    .filter((m): m is RegExpExecArray => !!m)
    .map((m) => `${m[1]}.${m[2]}.${m[3]}`);

async function scan(canvas: Canvas, view: string): Promise<Row[]> {
  const res = await new AxeBuilder({ page: canvas.page }).withTags(TAGS).exclude('iframe').analyze();
  await canvas.shot(`a11y-${view.toLowerCase().replace(/\W+/g, '-')}`);
  return res.violations.map((v) => ({
    view,
    id: v.id,
    impact: v.impact ?? 'n/a',
    criteria: criteriaOf(v.tags),
    help: v.help,
    url: v.helpUrl,
    targets: v.nodes.map((n) => n.target.map(String).join(' >> ')),
  }));
}

function report(rows: Row[]): string {
  const when = new Date().toISOString().slice(0, 10);
  const out: string[] = [
    '# Accessibility report: extension UI',
    '',
    `Generated by \`e2e/specs/a11y.spec.ts\` (axe-core 4.14 via @axe-core/playwright) on ${when}.`,
    'Scope: the canvas page only (app iframes excluded), against apps/demo with its config imported.',
    `Rule sets: ${TAGS.join(', ')}. WCAG 2.2 AA is the target (docs/BUILD_PLAN.md, "Accessibility of the extension UI").`,
    '',
    'Nothing here was fixed by the e2e work: components belong to the UI owners. Each row is a follow-up.',
    '',
  ];
  const views = [...new Set(rows.map((r) => r.view))];
  const total = rows.reduce((n, r) => n + r.targets.length, 0);
  out.push(`**${rows.length} violations (${total} nodes)** across ${views.length || 0} views.`, '');
  if (!rows.length) out.push('No violations found.');
  out.push('| View | Rule | Impact | WCAG 2.2 SC | Nodes | Selectors (first 5) |', '| --- | --- | --- | --- | --- | --- |');
  for (const r of rows) {
    const sc = r.criteria.length ? r.criteria.map((c) => `${c} ${SC[c] ?? ''}`.trim()).join('; ') : 'best practice (no SC)';
    const sel = r.targets
      .slice(0, 5)
      .map((t) => '`' + t.replace(/\|/g, '\\|').replace(/`/g, "'") + '`')
      .join('<br>');
    out.push(`| ${r.view} | [${r.id}](${r.url}): ${r.help.replace(/\|/g, '\\|')} | ${r.impact} | ${sc} | ${r.targets.length} | ${sel}${r.targets.length > 5 ? '<br>…' : ''} |`);
  }
  out.push(
    '',
    '## Not covered by axe (manual checks from the plan)',
    '',
    '- 2.1.1 Keyboard / 2.5.7 Dragging Movements: Tab through frames, Enter for the frame menu, E to start an edge, arrows to nudge.',
    '- 2.4.11 Focus Not Obscured, 1.4.11 focus ring contrast against the canvas.',
    '- 2.3.3 Animation from Interactions: Player and fly-to under `prefers-reduced-motion`.',
    '- Screen reader announcements of the canvas live region ("Catalog, empty state, 3 of 12").',
    '',
  );
  return out.join('\n');
}

test('axe: Player, Canvas with the edge inspector, Tokens panel', async ({ openCanvas }) => {
  const canvas = await openCanvas(DEMO);
  const config = demoConfig(DEMO);
  await canvas.importConfig(config);
  await canvas.waitReady('welcome:default');
  const rows: Row[] = [];

  rows.push(...(await scan(canvas, 'Player')));

  await canvas.setMode('Canvas');
  await expect.poll(() => canvas.fc((fc) => fc.rf?.getNodes().length ?? 0)).toBeGreaterThan(0);
  await canvas.centerOn(['welcome:default', 'pick-interests:default'], 0.6);
  await canvas.fc((fc) => fc.ui.getState().set({ selectedEdge: fc.project.getState().config.edges[0].id }));
  await expect(canvas.page.getByRole('complementary', { name: 'Edge inspector' })).toBeVisible();
  rows.push(...(await scan(canvas, 'Canvas + edge inspector')));
  await canvas.page.getByRole('button', { name: 'Close edge inspector' }).click();

  await canvas.page.getByRole('button', { name: /^Tokens/ }).click();
  await expect(canvas.page.getByRole('complementary', { name: 'Tokens' })).toBeVisible();
  await expect.poll(() => canvas.fc((fc) => (fc.ui.getState().baseTokens ?? []).length)).toBeGreaterThan(0);
  rows.push(...(await scan(canvas, 'Tokens panel')));

  const md = report(rows);
  fs.writeFileSync(path.join(E2E_DIR, 'a11y-report.md'), md);
  await test.info().attach('a11y-report.md', { body: md, contentType: 'text/markdown' });
  test.info().annotations.push({ type: 'a11y', description: `${rows.length} violations; see e2e/a11y-report.md` });
});
