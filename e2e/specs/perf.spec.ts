/**
 * Perf budget (docs/BUILD_PLAN.md "Performance budget"):
 *   - pan / zoom: 50 fps or more with 30 frames on the canvas
 *   - token broadcast: under 200 ms to 20 frames
 *
 * Headless Chromium in a container is not a 2021 MacBook Air, so by default the
 * assertions are tolerant (they catch regressions of an order of magnitude) and
 * the real numbers go to e2e/perf-report.md and the test annotations.
 * PERF_STRICT=1 asserts the plan's budget exactly (use on real hardware).
 */
import fs from 'node:fs';
import path from 'node:path';
import { demoConfig, expect, test, type Canvas } from '../fixtures';
import { DEMO, E2E_DIR } from '../fixtures/paths';

const STRICT = process.env.PERF_STRICT === '1';
const results: Record<string, unknown> = {};

interface Fps {
  frames: number;
  fps: number;
  avgMs: number;
  p95Ms: number;
  maxMs: number;
}

/** rAF frame times while an animated viewport pan runs (performance.measure marks the window). */
function panFps(canvas: Canvas, dx: number, ms = 1200): Promise<Fps> {
  return canvas.page.evaluate(
    async ([dx, ms]) => {
      const rf = (window as any).__fc.rf;
      const times: number[] = [];
      let last = performance.now();
      let run = true;
      const loop = (t: number) => {
        times.push(t - last);
        last = t;
        if (run) requestAnimationFrame(loop);
      };
      requestAnimationFrame(loop);
      performance.mark('fc-pan-start');
      const v = rf.getViewport();
      rf.setViewport({ x: v.x - dx, y: v.y, zoom: v.zoom }, { duration: ms });
      await new Promise((r) => setTimeout(r, ms));
      rf.setViewport({ x: v.x, y: v.y, zoom: v.zoom }, { duration: ms });
      await new Promise((r) => setTimeout(r, ms));
      performance.mark('fc-pan-end');
      performance.measure('fc-pan', 'fc-pan-start', 'fc-pan-end');
      run = false;
      const ft = times.slice(2).sort((a, b) => a - b);
      const avg = ft.reduce((a, b) => a + b, 0) / ft.length;
      const r2 = (n: number) => Math.round(n * 100) / 100;
      return { frames: ft.length, fps: r2(1000 / avg), avgMs: r2(avg), p95Ms: r2(ft[Math.floor(ft.length * 0.95)]!), maxMs: r2(ft[ft.length - 1]!) };
    },
    [dx, ms] as const,
  );
}

/** Frame nodes whose box intersects the visible flow area. */
function framesInView(canvas: Canvas): Promise<number> {
  return canvas.fc((fc) => {
    const rf = fc.rf;
    const { x, y, zoom } = rf.getViewport();
    const el = document.querySelector('.react-flow') as HTMLElement;
    const view = { x: -x / zoom, y: -y / zoom, w: el.clientWidth / zoom, h: el.clientHeight / zoom };
    return rf.getNodes().filter((n: any) => {
      if (n.type === 'section' || !String(n.id).includes(':')) return false;
      const b = rf.getInternalNode(n.id)?.internals.positionAbsolute ?? n.position;
      const w = n.measured?.width ?? 440;
      const h = n.measured?.height ?? 956;
      return b.x < view.x + view.w && b.x + w > view.x && b.y < view.y + view.h && b.y + h > view.y;
    }).length;
  });
}

async function openDemoCanvas(openCanvas: (o: string) => Promise<Canvas>) {
  const canvas = await openCanvas(DEMO);
  await canvas.importConfig(demoConfig(DEMO));
  await canvas.setMode('Canvas');
  await expect.poll(() => canvas.fc((fc) => fc.rf?.getNodes().length ?? 0)).toBeGreaterThan(30);
  return canvas;
}

