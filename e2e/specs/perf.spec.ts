test('pan fps with 30+ frames on the canvas', async ({ openCanvas }) => {
  const canvas = await openDemoCanvas(openCanvas);

  // Zoomed out: every frame on screen, all of them stills (zoom < 50%).
  await canvas.fc((fc) => fc.rf.fitView({ padding: 0.02 }));
  await canvas.page.waitForTimeout(1500);
  const overview = { framesInView: await framesInView(canvas), live: await canvas.fc((fc) => fc.ui.getState().live.size), ...(await panFps(canvas, 600)) };

  // Working zoom (50%): up to 12 live iframes plus stills around them.
  await canvas.centerOn(['catalog:default', 'catalog:error', 'product:default', 'wishlist:default'], 0.5);
  await canvas.page.waitForTimeout(4000); // let the live frames load
  const working = { framesInView: await framesInView(canvas), live: await canvas.fc((fc) => fc.ui.getState().live.size), ...(await panFps(canvas, 900)) };

  results.pan = { budget: '>= 50 fps with 30 frames', overview, working };
  test.info().annotations.push({ type: 'perf', description: `pan overview ${overview.fps} fps (${overview.framesInView} frames); working ${working.fps} fps (${working.live} live)` });
  await canvas.shot('perf-pan');

  expect(overview.framesInView).toBeGreaterThanOrEqual(30);
  expect(overview.fps).toBeGreaterThan(STRICT ? 50 : 15);
  expect(working.fps).toBeGreaterThan(STRICT ? 50 : 10);
});

test('token broadcast time to every live frame', async ({ openCanvas }) => {
  const canvas = await openDemoCanvas(openCanvas);
  // Force as many frames live as the live/still rule allows (MAX_LIVE = 12).
  const keys = await canvas.fc((fc) =>
    fc.project
      .getState()
      .config.screens.flatMap((s: any) => s.states.map((st: string) => `${s.id}:${st}`))
      .slice(0, 20) as string[],
  );
  await canvas.centerOn(keys.slice(0, 6), 0.5);
  await canvas.forceLive(keys);
  await expect.poll(() => canvas.fc((fc) => fc.ui.getState().live.size), { timeout: 20_000 }).toBeGreaterThanOrEqual(10);
  const live = await canvas.fc((fc) => [...fc.ui.getState().live] as string[]);
  for (const k of live) await canvas.waitReady(k, 30_000);
  const frames = await Promise.all(live.map((k) => canvas.waitFrame(k)));

  const runs: number[] = [];
  for (let i = 0; i < 5; i++) {
    const value = `${30 + i}px`;
    // In each frame: note when the bridge applies the var. (Not the next rAF: Chromium
    // throttles rAF in off-screen cross-origin iframes.) Gives up after 5 s (Infinity).
    const seen = frames.map((f) =>
      f.evaluate(
        (v) =>
          new Promise<number>((resolve) => {
            const el = document.documentElement;
            const now = () => performance.timeOrigin + performance.now();
            if (el.style.getPropertyValue('--text-display') === v) return resolve(now());
            const mo = new MutationObserver(() => {
              if (el.style.getPropertyValue('--text-display') === v) {
                mo.disconnect();
                resolve(now());
              }
            });
            mo.observe(el, { attributes: true, attributeFilter: ['style'] });
            setTimeout(() => resolve(Infinity), 5000);
          }),
        value,
      ),
    );
    await canvas.page.waitForTimeout(200); // observers are in place
    const t0 = await canvas.page.evaluate((v) => {
      performance.mark(`fc-token-${v}`);
      const t = performance.timeOrigin + performance.now();
      (window as any).__fc.ui.getState().set({ tokenDraft: { '--text-display': v } });
      return t;
    }, value);
    const ends = await Promise.all(seen);
    expect(ends.filter((e) => e === Infinity), 'frames that never got the token').toHaveLength(0);
    const ms = Math.max(...ends) - t0;
    await canvas.page.evaluate(
      ([v, end]) => performance.measure(`fc-token-broadcast-${v}`, { start: `fc-token-${v}`, end: end - performance.timeOrigin }),
      [value, Math.max(...ends)] as const,
    );
    runs.push(Math.round(ms * 10) / 10);
  }
  const sorted = [...runs].sort((a, b) => a - b);
  results.tokenBroadcast = { budget: '< 200 ms to 20 frames', frames: frames.length, note: 'live frames are capped at 12 (MAX_LIVE); stills get the tokens on their next capture', runsMs: runs, medianMs: sorted[2], maxMs: sorted[4] };
  test.info().annotations.push({ type: 'perf', description: `token broadcast to ${frames.length} frames: median ${sorted[2]} ms, max ${sorted[4]} ms` });

  expect(frames.length).toBeGreaterThanOrEqual(10);
  expect(sorted[2]!).toBeLessThan(STRICT ? 200 : 1000);
});
